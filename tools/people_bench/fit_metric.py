#!/usr/bin/env python3
"""Fit the constants of the app's face metric (FaceMetric.kt) on stranger faces.

- mean: the mean of all unit vectors. SFace vectors share a direction (mean
  pair cosine about 0.075), which lets a mixed group's centroid resemble
  everyone. The app subtracts it and re-normalises.
- prototypes: K spherical k-means centres of the centred vectors. A face's
  "crowd" is its best cosine to a prototype minus the median face's; faces in
  a crowded region (babies and toddlers above all) match many strangers, and
  the app raises the bar for them by that amount.

Each prototype averages at least --min-support faces of different people, so
the file holds no individual's vector. Writes SFaceMetricData.kt and prints a
JSON summary of aggregates.
"""
import argparse
import base64
import hashlib
import json
import sys

import numpy as np

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from impostor_stats import load  # noqa: E402


def unit(a):
    return a / np.linalg.norm(a, axis=-1, keepdims=True)


def kmeans(x, k, iters=50, seed=0):
    rng = np.random.default_rng(seed)
    c = x[rng.choice(len(x), k, replace=False)].copy()
    for _ in range(iters):
        a = (x @ c.T).argmax(1)
        for j in range(k):
            m = x[a == j]
            if len(m):
                c[j] = m.sum(0)
        c = unit(c)
    return c, np.bincount((x @ c.T).argmax(1), minlength=k)


def quantise(rows):
    """int8 with one scale per row, like FaceEmbedding; returns bytes, scales, decoded."""
    scale = np.abs(rows).max(1, keepdims=True) / 127.0
    q = np.clip(np.rint(rows / scale), -127, 127).astype(np.int8)
    return q, scale[:, 0].astype(np.float32), unit(q * scale)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--part", nargs=3, action="append", metavar=("WORK", "LICENSED", "META"), required=True)
    ap.add_argument("--k", type=int, default=32)
    ap.add_argument("--min-support", type=int, default=20)
    ap.add_argument("--kotlin", required=True, help="output SFaceMetricData.kt")
    ap.add_argument("--npz", help="optional: also save the fitted arrays for the bench scripts")
    a = ap.parse_args()
    v = load(a.part)[0]
    mean = v.mean(0).astype(np.float32)
    c = unit(v - mean)
    protos, support = kmeans(c, a.k)
    keep = support >= a.min_support
    q, scales, decoded = quantise(protos[keep])
    crowd = (c @ decoded.T).max(1)
    baseline = float(np.float32(np.median(crowd)))
    blob = mean.astype("<f4").tobytes() + scales.astype("<f4").tobytes() + q.tobytes()
    digest = hashlib.sha256(blob).hexdigest()
    b64 = base64.b64encode(blob).decode()
    lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    with open(a.kotlin, "w") as f:
        f.write("package nl.atlas.gallery.featurepeople.cluster\n\n")
        f.write("/**\n * Generated by tools/people_bench/fit_metric.py; do not edit by hand.\n"
                f" * Fitted on {len(v)} faces of strangers from CC BY 2.0 Open Images photos.\n"
                " * Holds a mean vector and prototypes that each average at least\n"
                f" * {int(support[keep].min())} different people: no individual's vector.\n */\n")
        f.write("internal object SFaceMetricData {\n")
        f.write(f"    const val DIMENSION = {v.shape[1]}\n")
        f.write(f"    const val PROTOTYPES = {int(keep.sum())}\n")
        f.write(f"    const val BASELINE = {baseline!r}f\n")
        f.write(f"    const val SHA256 = \"{digest}\"\n")
        f.write("    /** Little-endian: mean (float32 x DIMENSION), one float32 scale per prototype, int8 rows. */\n")
        f.write("    val BASE64: String = listOf(\n")
        for ln in lines:
            f.write(f"        \"{ln}\",\n")
        f.write("    ).joinToString(\"\")\n}\n")
    if a.npz:
        np.savez(a.npz, mean=mean, protos=decoded, baseline=baseline)
    print(json.dumps({"faces": int(len(v)), "prototypes": int(keep.sum()),
                      "min_support": int(support[keep].min()), "baseline": baseline,
                      "mean_norm": float(np.linalg.norm(mean)), "sha256": digest,
                      "crowd_excess_percentiles_75_90_95_99":
                          [float(x) for x in np.percentile(np.maximum(0, crowd - baseline), [75, 90, 95, 99])]}))


if __name__ == "__main__":
    main()
