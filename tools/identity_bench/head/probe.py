def cmd_swap(args) -> int:
    import cv2
    models, out = Path(args.models), Path(args.out)
    judge = Judge(models)
    if args.engine == "composite":
        engine = CompositeEngine()
    else:
        engine = KleinEngine(models, args.quant, lora=args.engine == "klein-lora", threads=args.threads)
    dest = out / engine.name
    dest.mkdir(parents=True, exist_ok=True)
    for pair, tgt, ref, why in PAIRS:
        if args.pairs and pair not in args.pairs:
            continue
        target, reference = _read(out / "fixtures" / f"{tgt}.png"), _read(out / "fixtures" / f"{ref}.png")
        res = engine.swap(judge, target, reference, seed=args.seed)
        cv2.imwrite(str(dest / f"{pair}_raw.png"), res["raw"])
        final = res["final"] if res["final"] is not None else res["raw"]
        cv2.imwrite(str(dest / f"{pair}.png"), final)
        rec = {"schema": SCHEMA, "engine": engine.name, "pair": pair, "target": tgt, "reference": ref, "why": why,
               "seed": args.seed, "tokens": res["tokens"], "seconds": res["seconds"], "load_s": round(engine.load_s, 1),
               "peak_rss_mb": peak_rss_mb(), "host": host_info(),
               "score": judge.score(target, reference, final),
               "score_raw": judge.score(target, reference, res["raw"])}
        (dest / f"{pair}.json").write_text(json.dumps(rec, indent=1))
        print(pair, classify(rec["score"]), json.dumps(rec["seconds"]), rec["peak_rss_mb"], flush=True)
    return 0


def load_records(out: Path) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(out.glob("*/p*.json"))]


def cmd_repaste(args) -> int:
    """Rebuild each pasted-back result from the saved raw model output (no generation)."""
    import cv2
    out, judge = Path(args.out), Judge(Path(args.models))
    for path in sorted(out.glob("klein*/p*.json")):
        rec = json.loads(path.read_text())
        target = _read(out / "fixtures" / f"{rec['target']}.png")
        raw = _read(path.with_name(f"{rec['pair']}_raw.png"))
        t = time.time()
        final = judge.composite(target, raw)
        rec["seconds"]["paste"] = round(time.time() - t, 2)
        cv2.imwrite(str(path.with_suffix(".png")), final if final is not None else raw)
        path.write_text(json.dumps(rec, indent=1))
        print("repasted", rec["engine"], rec["pair"])
    return 0


def cmd_rescore(args) -> int:
    """Recompute every score from the saved PNGs (lossless), keeping timings."""
    out, judge = Path(args.out), Judge(Path(args.models))
    for path in sorted(out.glob("*/p*.json")):
        rec = json.loads(path.read_text())
        target = _read(out / "fixtures" / f"{rec['target']}.png")
        reference = _read(out / "fixtures" / f"{rec['reference']}.png")
        rec["score"] = judge.score(target, reference, _read(path.with_suffix(".png")))
        rec["score_raw"] = judge.score(target, reference, _read(path.with_name(f"{rec['pair']}_raw.png")))
        path.write_text(json.dumps(rec, indent=1))
        print(rec["engine"], rec["pair"], classify(rec["score"]))
    return 0


def cmd_export(args) -> int:
    """Write the committed evidence file: records, anchor and summary."""
    out = Path(args.out)
    records = load_records(out)
    anchors = [json.loads(p.read_text()) for p in sorted(out.glob("anchor_*.json"))]
    anchor = anchors[0]
    anchor["median_step_s"] = _median(anchor["steps"])
    fixtures = {}
    for p in sorted((out / "fixtures").glob("*log*.json")):
        fixtures.update(json.loads(p.read_text())["items"])
    data = {"schema": SCHEMA, "anchor": anchor, "fixtures": fixtures, "records": records, "summary": summarise(records)}
    Path(args.json).write_text(json.dumps(data, indent=1) + "\n")
    print(args.json, len(records), "records")
    return 0


def cmd_report(args) -> int:
    out = Path(args.out)
    records = load_records(out)
    anchor = None
    for p in sorted(out.glob("anchor_*.json")):
        steps = json.loads(p.read_text())["steps"]
        anchor = _median(steps)
    print(render_report(records, anchor))
    if anchor:
        print(f"\nHost anchor: {anchor} s per step at 512x512 text-to-image; phone factor {phone_factor(anchor)}")
    return 0


def cmd_sheet(args) -> int:
    """Contact sheet per pair: target, reference, then each engine's result."""
    import cv2
    import numpy as np
    out, edge = Path(args.out), args.edge
    engines = sorted(p.name for p in out.iterdir() if p.is_dir() and p.name != "fixtures" and any(p.glob("p*.png")))
    rows = []
    for pair, tgt, ref, _ in PAIRS:
        cells = [("target", out / "fixtures" / f"{tgt}.png"), ("reference", out / "fixtures" / f"{ref}.png")]
        cells += [(e, out / e / f"{pair}.png") for e in engines]
        row = []
        for label, path in cells:
            img = cv2.imread(str(path)) if path.exists() else None
            cell = np.full((edge, edge, 3), 40, np.uint8) if img is None else cv2.resize(img, (edge, edge), interpolation=cv2.INTER_AREA)
            cv2.rectangle(cell, (0, 0), (edge, 22), (0, 0, 0), -1)
            cv2.putText(cell, f"{pair} {label}"[:44], (4, 16), cv2.FONT_HERSHEY_SIMPLEX, 0.42, (255, 255, 255), 1, cv2.LINE_AA)
            row.append(cell)
        rows.append(np.hstack(row))
    sheet = np.vstack(rows)
    cv2.imwrite(str(Path(args.sheet)), sheet, [cv2.IMWRITE_JPEG_QUALITY, args.quality])
    print(args.sheet, sheet.shape)
    return 0


