def head_crop_box(face, width: int, height: int, scale: float = 3.4) -> tuple[int, int, int, int]:
    """Square crop around the head, clamped to the image, as (x0, y0, x1, y1)."""
    x, y, bw, bh = (float(v) for v in face[:4])
    side = int(min(scale * max(bw, bh), width, height))
    cx, cy = x + bw / 2, y + bh / 2 - 0.1 * bh
    x0 = int(min(max(cx - side / 2, 0), width - side))
    y0 = int(min(max(cy - side / 2, 0), height - side))
    return x0, y0, x0 + side, y0 + side


class KleinEngine:
    """FLUX.2 klein 4B (GGUF) through stable-diffusion.cpp, optionally with the head-swap LoRA.

    Works on a square crop around the target head, then pastes the result
    back so pixels outside the edit mask stay bit-identical.
    """

    STEPS = 4  # the distilled model's own step count

    def __init__(self, models: Path, quant: str, lora: bool, threads: int, edge: int = 512):
        from stable_diffusion_cpp import StableDiffusion
        self.name = f"klein4b-{quant}" + ("-headlora" if lora else "-prompt-only")
        self.lora, self.edge, self.steps = lora, edge, []
        t = time.time()
        self.sd = StableDiffusion(
            diffusion_model_path=str(models / f"klein-{quant}.gguf"),
            llm_path=str(models / "qwen3-4b-Q4_K_M.gguf"),
            vae_path=str(models / "flux2_vae.safetensors"),
            lora_model_dir=str(models / "loras") if lora else "",
            n_threads=threads, verbose=False)
        self.load_s = time.time() - t

    def _generate(self, **kw):
        self.steps = []
        last = [time.time()]

        def on_step(step, steps, _time):
            now = time.time()
            self.steps.append(round(now - last[0], 1))
            last[0] = now
        t = time.time()
        img = self.sd.generate_image(cfg_scale=1.0, sample_steps=self.STEPS, progress_callback=on_step, **kw)[0]
        # The callback also fires for encoder and VAE progress; the denoise steps are the last ones.
        self.steps = self.steps[-self.STEPS:]
        return img, time.time() - t

    def text_to_image(self, prompt: str, size: int, seed: int):
        return self._generate(prompt=prompt, width=size, height=size, seed=seed)

    def swap(self, judge: Judge, target, reference, seed: int):
        import cv2
        import numpy as np
        from PIL import Image
        t0 = time.time()
        h, w = target.shape[:2]
        x0, y0, x1, y1 = head_crop_box(judge.face(target), w, h)
        rf = judge.face(reference)
        rx0, ry0, rx1, ry1 = head_crop_box(rf, reference.shape[1], reference.shape[0], scale=3.0)
        to_pil = lambda bgr: Image.fromarray(cv2.cvtColor(cv2.resize(bgr, (self.edge, self.edge), interpolation=cv2.INTER_AREA), cv2.COLOR_BGR2RGB))
        crop = target[y0:y1, x0:x1]
        prompt = HEAD_SWAP_PROMPT + (" <lora:bfs_head_v1:1.0>" if self.lora else "")
        prep_s = time.time() - t0
        out, gen_s = self._generate(prompt=prompt, ref_images=[to_pil(crop), to_pil(reference[ry0:ry1, rx0:rx1])],
                                    increase_ref_index=True, width=self.edge, height=self.edge, seed=seed)
        t1 = time.time()
        raw_crop = cv2.resize(cv2.cvtColor(np.asarray(out), cv2.COLOR_RGB2BGR), (x1 - x0, y1 - y0), interpolation=cv2.INTER_CUBIC)
        raw = target.copy()
        raw[y0:y1, x0:x1] = raw_crop
        final = judge.composite(target, raw)
        return {"raw": raw, "final": final,
                "seconds": {"prepare": round(prep_s, 2), "generate": round(gen_s, 1), "paste": round(time.time() - t1, 2),
                            "steps": list(self.steps), "total": round(time.time() - t0, 1)},
                "tokens": edit_tokens((self.edge, self.edge), [(self.edge, self.edge)] * 2)}


class CompositeEngine:
    """The no-generation floor: cut the reference head out and paste it on.

    Similarity-aligns the reference head to the target face from the five
    detector landmarks, copies head pixels (face, ears, hair), matches skin
    colour in Lab, and feathers the seam. It cannot change head pose, cannot
    remove the target's own hair and cannot invent background, which is the
    point: this is what "no generative model" buys on the phone.
    """
    name = "composite-floor"
    load_s = 0.0

    def __init__(self, *_a, **_k):
        pass

    def swap(self, judge: Judge, target, reference, seed: int):
        import cv2
        import numpy as np
        t0 = time.time()
        t, r = judge.describe(target), judge.describe(reference)
        src = np.asarray(r["f"][4:14], np.float32).reshape(5, 2)
        dst = np.asarray(t["f"][4:14], np.float32).reshape(5, 2)
        m, _ = cv2.estimateAffinePartial2D(src, dst, method=cv2.LMEDS)
        h, w = target.shape[:2]
        warped = cv2.warpAffine(reference, m, (w, h), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT_101)
        mask = cv2.warpAffine(r["head"].astype(np.uint8) * 255, m, (w, h), flags=cv2.INTER_LINEAR)
        alpha = cv2.GaussianBlur(mask.astype(np.float32) / 255, (0, 0), 3)[..., None]
        out = (alpha * warped + (1 - alpha) * target).round().astype(np.uint8)
        total = round(time.time() - t0, 3)
        return {"raw": out, "final": out, "tokens": 0,
                "seconds": {"prepare": 0.0, "generate": total, "paste": 0.0, "steps": [], "total": max(total, 0.001)}}


def _read(path: Path):
    import cv2
    img = cv2.imread(str(path))
    if img is None:
        raise FileNotFoundError(path)
    return img


def cmd_fixtures(args) -> int:
    out = Path(args.out) / "fixtures"
    out.mkdir(parents=True, exist_ok=True)
    engine = KleinEngine(Path(args.models), args.quant, lora=False, threads=args.threads)
    log = {"schema": SCHEMA, "engine": engine.name, "host": host_info(), "load_s": round(engine.load_s, 1), "items": {}}
    for i, (name, prompt) in enumerate(FIXTURES.items()):
        if (out / f"{name}.png").exists():
            continue
        img, secs = engine.text_to_image(prompt + STYLE, FIXTURE_SIZE, FIXTURE_SEED + i)
        img.save(out / f"{name}.png")
        log["items"][name] = {"seconds": round(secs, 1), "steps": list(engine.steps), "seed": FIXTURE_SEED + i,
                              "licence": "synthetic; generated by this probe with FLUX.2 klein 4B (Apache-2.0); depicts no real person"}
        log["peak_rss_mb"] = peak_rss_mb()
        (out / "fixtures_log.json").write_text(json.dumps(log, indent=1))
        print(name, log["items"][name], flush=True)
    return 0


def cmd_anchor(args) -> int:
    """512x512 text-to-image step time: the workload the phone anchor was measured on."""
    engine = KleinEngine(Path(args.models), args.quant, lora=False, threads=args.threads)
