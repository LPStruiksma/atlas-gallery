# OpenCV's published SFace cosine threshold for "same identity" (LFW).
SFACE_SAME_IDENTITY = 0.363
# Thresholds fixed on 2026-11-18 before the first generative run, after the
# judge self-test showed that two DIFFERENT synthetic people already score
# 0.33-0.40 with SFace (above the published threshold). So a swap must beat
# the target by a margin, and "convincing" must clear both an absolute bar
# and the impostor floor of its own pair.
ID_MARGIN_OVER_TARGET = 0.15
ID_CONVINCING = 0.60
ID_MARGIN_OVER_IMPOSTOR = 0.20
# Added after the first run, when the cut-and-paste floor pasted a head beside
# the old one and the rule above still called it a full head. See FULL_HEAD.md §5.
TARGET_HEAD_MAY_REMAIN = 0.25


def latent_tokens(width: int, height: int) -> int:
    """Transformer tokens for one image: 16x16 pixels per token (8x VAE, 2x2 patch)."""
    if width % 16 or height % 16 or width <= 0 or height <= 0:
        raise ValueError("width and height must be positive multiples of 16")
    return (width // 16) * (height // 16)


def edit_tokens(out_wh: tuple[int, int], refs_wh: list[tuple[int, int]]) -> int:
    """Image tokens the denoiser attends over in one step: the output plus every reference."""
    return latent_tokens(*out_wh) + sum(latent_tokens(*wh) for wh in refs_wh)


def classify(score: dict) -> str:
    """Name what an output actually is. Face-only is never counted as full head.

    full_head : identity moved to the reference AND the hair followed it AND
                the target's own head is gone.
    target_head_remains : a new head was added but much of the old one is
                still visible (the cut-and-paste failure).
    face_only : identity moved but the hair stayed the target's.
    no_swap   : identity did not clearly move from the target to the reference.
    failed    : no face found in the output.
    """
    if not score.get("face_found"):
        return "failed"
    to_ref, to_tgt = score["id_to_reference"], score["id_to_target"]
    if to_ref < SFACE_SAME_IDENTITY or to_ref - to_tgt < ID_MARGIN_OVER_TARGET:
        return "no_swap"
    if not hair_followed_reference(score):
        return "face_only"
    if score.get("target_head_unchanged_frac", 0.0) > TARGET_HEAD_MAY_REMAIN:
        return "target_head_remains"
    return "full_head"


HAS_HAIR = 0.10  # hair pixels over face-box area below this counts as bald


def hair_followed_reference(score: dict) -> bool:
    """Did the hair become the reference's rather than stay the target's?

    When reference, target and result all have hair, colour decides: a
    face-only result keeps the target's hair colour exactly. Hair amount is
    used only when one side is bald, because the amount depends on framing
    (a close-up reference shows more of its hair than a waist-up target).
    Revised after the first run; see FULL_HEAD.md section 5.
    """
    r = score["hair_ratio"]
    d_ref, d_tgt = score.get("hair_dE_to_reference"), score.get("hair_dE_to_target")
    if min(r["reference"], r["target"], r["result"]) >= HAS_HAIR and d_ref is not None and d_tgt is not None:
        return d_ref < d_tgt
    return abs(r["result"] - r["reference"]) < abs(r["result"] - r["target"])


POSE_TOLERANCE = 0.30  # allowed change of the head-turn proxy; a head facing elsewhere than the body is not a swap


def pose_kept(score: dict) -> bool:
    yaw = score.get("yaw")
    return yaw is None or abs(yaw["result"] - yaw["target"]) <= POSE_TOLERANCE


def convincing(score: dict) -> bool:
    """Full head, target pose kept, identity above the absolute bar and its pair's impostor floor."""
    if classify(score) != "full_head" or not pose_kept(score):
        return False
    to_ref = score["id_to_reference"]
    return to_ref >= ID_CONVINCING and to_ref - score["id_reference_vs_target"] >= ID_MARGIN_OVER_IMPOSTOR


def summarise(records: list[dict]) -> dict:
    """Per-engine counts and medians. Failures stay in the denominator."""
    out: dict[str, dict] = {}
    for rec in records:
        validate_record(rec)
        e = out.setdefault(rec["engine"], {"n": 0, "classes": {}, "_id": [], "_s": [], "peak_rss_mb": 0, "convincing": 0})
        e["n"] += 1
        cls = classify(rec["score"])
        e["classes"][cls] = e["classes"].get(cls, 0) + 1
        e["convincing"] += int(convincing(rec["score"]))
        if rec["score"].get("face_found"):
            e["_id"].append(rec["score"]["id_to_reference"])
        e["_s"].append(rec["seconds"]["total"])
        e["peak_rss_mb"] = max(e["peak_rss_mb"], rec["peak_rss_mb"])
    for e in out.values():
        ids, secs = e.pop("_id"), e.pop("_s")
        e["median_id_to_reference"] = round(_median(ids), 3) if ids else None
        e["median_seconds"] = round(_median(secs), 1)
    return out


def _median(values: list[float]) -> float:
    s = sorted(values)
    m = len(s) // 2
    return s[m] if len(s) % 2 else (s[m - 1] + s[m]) / 2


def validate_record(rec: dict) -> None:
    for key in ("schema", "engine", "pair", "seconds", "peak_rss_mb", "score", "host"):
        if key not in rec:
            raise ValueError(f"record lacks {key!r}")
    if rec["schema"] != SCHEMA:
        raise ValueError(f"unknown schema {rec['schema']!r}")
    if "total" not in rec["seconds"] or rec["seconds"]["total"] <= 0:
        raise ValueError("seconds.total must be positive")
    if rec["peak_rss_mb"] <= 0:
        raise ValueError("peak_rss_mb must be positive")


# ---- S24+ extrapolation ----------------------------------------------------
# The phone has no measured number of its own yet, so every estimate is a
# range built from: (1) a host measurement taken by this probe, (2) a
# community measurement of the same denoiser on a phone CPU, (3) a stated
# SoC ratio. Replace (2) and (3) with an on-device run when one exists.
PHONE = {
    "name": "Galaxy S24+ (Exynos 2400, 12 GB)",
    "ram_mb": 12 * 1024,
    # What one foreground app can hold before Android's low-memory killer
    # becomes likely on a 12 GB phone with the gallery itself loaded. A
    # planning assumption, not a measurement.
    "app_budget_mb": (5000, 7000),
    # Usable accelerators for this model class, per RESEARCH.md §5.
    "accelerators": "CPU only for large transformers (no public NPU path on Exynos 2400)",
}
# duration-ai/bonsai-image-android README: Galaxy S25+ (Snapdragon 8 Elite),
# sd-cli on CPU, FLUX.2 klein 4B denoiser, 512x512 text-to-image.
ANCHOR_PHONE_STEP_S = 114.0
ANCHOR_TOKENS = 1024
# Snapdragon 8 Elite versus Exynos 2400 multi-core throughput. Assumption
# (public benchmark listings put the ratio near 1.4); the range is wide on
# purpose, and sustained load throttles the Exynos further.
SOC_SLOWDOWN = (1.3, 2.0)


def phone_factor(host_anchor_step_s: float) -> tuple[float, float]:
    """How many times slower the S24+ CPU is than this host, as a range.

    host_anchor_step_s is this host's measured seconds per step for the same
    workload as the phone anchor (512x512 text-to-image, 1024 tokens).
    """
    if host_anchor_step_s <= 0:
        raise ValueError("host_anchor_step_s must be positive")
    base = ANCHOR_PHONE_STEP_S / host_anchor_step_s
    return (base * SOC_SLOWDOWN[0], base * SOC_SLOWDOWN[1])


def extrapolate_phone(host_seconds: float, host_anchor_step_s: float) -> dict:
    lo, hi = phone_factor(host_anchor_step_s)
    return {"low_s": round(host_seconds * lo), "high_s": round(host_seconds * hi),
            "factor": (round(lo, 2), round(hi, 2))}


def memory_fit(peak_rss_mb: int) -> str:
    """fits / tight / no, against the planning budget for one app on the phone."""
    low, high = PHONE["app_budget_mb"]
    if peak_rss_mb <= low:
        return "fits"
    return "tight" if peak_rss_mb <= high else "no"


def cost_per_edit(seconds_per_candidate: float, candidates: int, usd_per_hour: float,
                  cold_start_s: float = 0.0) -> float:
    """Rented-GPU cost of one edit (several candidates), billed per second."""
    if min(seconds_per_candidate, usd_per_hour) < 0 or candidates < 1 or cold_start_s < 0:
        raise ValueError("invalid cost inputs")
    return round((seconds_per_candidate * candidates + cold_start_s) * usd_per_hour / 3600, 5)


def render_report(records: list[dict], host_anchor_step_s: float | None) -> str:
    lines = ["| Engine | Pair | Class | Convincing | ID to reference | ID to target | Impostor floor | Head turn (target / result) | Old head left | Pixels changed | Seconds | Peak RSS MB |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for rec in records:
        s = rec["score"]
        if s.get("face_found"):
            yaw = s.get("yaw") or {"target": float("nan"), "result": float("nan")}
            row = (f"{'yes' if convincing(s) else 'no'} | {s['id_to_reference']:.3f} | {s['id_to_target']:.3f} | "
                   f"{s['id_reference_vs_target']:.3f} | {yaw['target']:+.2f} / {yaw['result']:+.2f} | "
                   f"{s.get('target_head_unchanged_frac', float('nan')):.0%} | {s.get('pixels_changed_frac', float('nan')):.0%}")
        else:
            row = "no | n/a | n/a | n/a | n/a | n/a | n/a"
        lines.append(f"| {rec['engine']} | {rec['pair']} | {classify(s)} | {row} | "
                     f"{rec['seconds']['total']:.0f} | {rec['peak_rss_mb']} |")
    lines.append("")
    for engine, e in summarise(records).items():
        line = (f"- **{engine}**: {e['classes']} of {e['n']}; convincing {e['convincing']}/{e['n']}; "
                f"median ID to reference {e['median_id_to_reference']}; median {e['median_seconds']} s; "
                f"peak {e['peak_rss_mb']} MB (phone memory: {memory_fit(e['peak_rss_mb'])})")
        if host_anchor_step_s:
            p = extrapolate_phone(e["median_seconds"], host_anchor_step_s)
            line += f"; S24+ estimate {p['low_s']}-{p['high_s']} s per candidate"
        lines.append(line)
    return "\n".join(lines)


