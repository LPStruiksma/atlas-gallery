class Judge:
    HAIR, NECK = 13, 17
    SKIN = (1, 2, 10, 11, 12)
    HEAD = tuple(range(1, 16))  # skin, features, ears, hair, hat, earring: no neck, no clothes

    def __init__(self, models: Path):
        import cv2
        import numpy as np
        import onnxruntime as ort
        self.cv2, self.np = cv2, np
        j = models / "judge"
        self.det = cv2.FaceDetectorYN.create(str(j / "yunet.onnx"), "", (320, 320), 0.6, 0.3, 50)
        self.rec = cv2.FaceRecognizerSF.create(str(j / "sface.onnx"), "")
        opts = ort.SessionOptions()
        opts.intra_op_num_threads = 2
        self.seg = ort.InferenceSession(str(j / "faceparse.onnx"), opts, providers=["CPUExecutionProvider"])

    def face(self, img):
        h, w = img.shape[:2]
        self.det.setInputSize((w, h))
        _, faces = self.det.detect(img)
        if faces is None or len(faces) == 0:
            return None
        return max(faces, key=lambda r: r[2] * r[3])

    def parse(self, img, f):
        """Face-parsing labels at image size, computed on a 3.2x face-box crop."""
        cv2, np = self.cv2, self.np
        h, w = img.shape[:2]
        x, y, bw, bh = f[:4]
        cx, cy, s = x + bw / 2, y + bh / 2, 3.2 * max(bw, bh)
        x0, y0, x1, y1 = (int(round(v)) for v in (cx - s / 2, cy - s / 2, cx + s / 2, cy + s / 2))
        ox, oy = max(0, -x0), max(0, -y0)
        pad = cv2.copyMakeBorder(img, oy, max(0, y1 - h), ox, max(0, x1 - w), cv2.BORDER_REFLECT_101)
        crop = pad[y0 + oy:y1 + oy, x0 + ox:x1 + ox]
        inp = cv2.cvtColor(cv2.resize(crop, (512, 512), interpolation=cv2.INTER_AREA), cv2.COLOR_BGR2RGB)
        inp = ((inp.astype(np.float32) / 255 - [0.485, 0.456, 0.406]) / [0.229, 0.224, 0.225])
        logits = self.seg.run(None, {self.seg.get_inputs()[0].name: inp.transpose(2, 0, 1)[None].astype(np.float32)})[0][0]
        lab = cv2.resize(logits.transpose(1, 2, 0), (crop.shape[1], crop.shape[0])).argmax(2).astype(np.uint8)
        full = np.zeros((h, w), np.uint8)
        ys0, xs0, ys1, xs1 = max(y0, 0), max(x0, 0), min(y1, h), min(x1, w)
        full[ys0:ys1, xs0:xs1] = lab[ys0 - y0:ys1 - y0, xs0 - x0:xs1 - x0]
        return full

    def _lab_mean(self, img, mask):
        if mask.sum() < 200:
            return None
        return self.cv2.cvtColor(img, self.cv2.COLOR_BGR2LAB).astype(self.np.float32)[mask].mean(0)

    def _dE(self, a, b):
        if a is None or b is None:
            return None
        return round(float(self.np.linalg.norm((a - b) * self.np.array([100 / 255, 1, 1]))), 2)

    @staticmethod
    def _yaw(f) -> float:
        (rx, ry), (lx, ly), (nx, _ny) = (f[4], f[5]), (f[6], f[7]), (f[8], f[9])
        eye = math.hypot(lx - rx, ly - ry) or 1.0
        return round(float((nx - (rx + lx) / 2) / eye), 2)

    def describe(self, img):
        np = self.np
        f = self.face(img)
        if f is None:
            return None
        lab = self.parse(img, f)
        hair, head = lab == self.HAIR, np.isin(lab, self.HEAD)
        emb = self.rec.feature(self.rec.alignCrop(img, f)).flatten()
        return {"f": f, "emb": emb / np.linalg.norm(emb), "head": head, "hair": hair,
                "hair_ratio": float(hair.sum() / (f[2] * f[3])),
                "hair_lab": self._lab_mean(img, hair),
                "skin_lab": self._lab_mean(img, np.isin(lab, self.SKIN)),
                "neck_lab": self._lab_mean(img, lab == self.NECK)}

    def edit_mask(self, target, result, grow=21, blur=15, level=18):
        """The region an engine may change: both heads plus whatever it visibly changed next to them.

        The face parser alone is not enough: it works on a crop around the
        face and misses long hair below it, so restoring "everything outside
        the head mask" would put the target's hair ends back. Any area where
        the engine's output differs clearly from the target and that touches
        the head region therefore joins the mask (removed hair, new hair, the
        background or clothing invented behind it).
        """
        cv2, np = self.cv2, self.np
        t, o = self.describe(target), self.describe(result)
        if t is None or o is None:
            return None
        heads = (t["head"] | o["head"]).astype(np.uint8)
        diff = np.abs(target.astype(np.int16) - result.astype(np.int16)).max(2).astype(np.float32)
        changed = (cv2.blur(diff, (blur, blur)) > level).astype(np.uint8)
        changed = cv2.morphologyEx(changed, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
        _, labels = cv2.connectedComponents((changed | heads).astype(np.uint8))
        keep = np.isin(labels, np.unique(labels[heads > 0])) & (labels > 0)
        return cv2.dilate(keep.astype(np.uint8), np.ones((grow, grow), np.uint8))

    def composite(self, target, result):
        """Keep every target pixel outside the edit mask bit-identical; feather just inside its edge."""
        cv2, np = self.cv2, self.np
        mask = self.edit_mask(target, result)
        if mask is None:
            return None
        alpha = cv2.GaussianBlur(cv2.erode(mask, np.ones((9, 9), np.uint8)).astype(np.float32), (0, 0), 4)[..., None]
        out = (alpha * result + (1 - alpha) * target).round().astype(np.uint8)
        out[mask == 0] = target[mask == 0]
        return out

    def score(self, target, reference, result) -> dict:
        np = self.np
        t, r, o = self.describe(target), self.describe(reference), self.describe(result)
        if t is None or r is None:
            raise ValueError("no face in a fixture")
        if o is None:
            return {"face_found": False}
        union = self.cv2.dilate((t["head"] | o["head"]).astype(np.uint8), np.ones((25, 25), np.uint8)).astype(bool)
        diff = target.astype(np.float32) - result.astype(np.float32)
        outside = ~union
        mse = float((diff[outside] ** 2).mean())
        ft, fo = t["f"], o["f"]
        return {
            "face_found": True,
            "id_to_reference": round(float(o["emb"] @ r["emb"]), 3),
            "id_to_target": round(float(o["emb"] @ t["emb"]), 3),
            "id_reference_vs_target": round(float(r["emb"] @ t["emb"]), 3),
            "hair_ratio": {"target": round(t["hair_ratio"], 2), "reference": round(r["hair_ratio"], 2),
                           "result": round(o["hair_ratio"], 2)},
            "hair_dE_to_reference": self._dE(o["hair_lab"], r["hair_lab"]),
            "hair_dE_to_target": self._dE(o["hair_lab"], t["hair_lab"]),
            "skin_dE_to_reference": self._dE(o["skin_lab"], r["skin_lab"]),
            "skin_dE_to_target": self._dE(o["skin_lab"], t["skin_lab"]),
            "face_neck_dE": {"target": self._dE(t["skin_lab"], t["neck_lab"]),
                             "result": self._dE(o["skin_lab"], o["neck_lab"])},
            # Head turn proxy from the five landmarks: nose offset from the eye midpoint over eye distance.
            "yaw": {"target": self._yaw(ft), "result": self._yaw(fo)},
            "face_scale_vs_target": round(math.sqrt(float(fo[2] * fo[3]) / float(ft[2] * ft[3])), 3),
            "face_centre_shift": round(float(np.hypot(fo[0] + fo[2] / 2 - ft[0] - ft[2] / 2,
                                                      fo[1] + fo[3] / 2 - ft[1] - ft[3] / 2) / ft[2]), 3),
            "outside_psnr_db": 99.0 if mse == 0 else round(10 * math.log10(255 ** 2 / mse), 2),
            "outside_changed_frac": round(float((np.abs(diff[outside]).max(1) > 8).mean()), 4),
            "edit_region_frac": round(float(union.mean()), 4),
            # Share of ALL pixels that differ from the source at all; the rest are bit-identical.
            # Share of the target's own head (face, ears, hair) left as it was: a pasted-on
            # head that leaves the old one visible must not pass as a head swap.
            "target_head_unchanged_frac": round(float((np.abs(diff[t["head"]]).max(1) <= 8).mean()), 3),
            "pixels_changed_frac": round(float((np.abs(diff).max(2) > 0).mean()), 4),
        }


