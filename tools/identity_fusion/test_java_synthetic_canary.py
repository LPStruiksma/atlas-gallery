#!/usr/bin/env python3
"""Cross-language synthetic Intel resize goldens; zero private model/photo IO.

Only JDK, optional Pillow and disposable synthetic RGB fixtures used.
Never compiles into app, loads model, or touches device / gallery.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

from audit_intel_resize_goldens import REFERENCE_SHA256
from synthetic_pillow_bilinear_reference import synthetic_pillow_bilinear
from benchmark_resize_parity import PROBES, TARGET, artificial_rgb

ROOT = Path(__file__).resolve().parent

# This TEST-ONLY Java harness reads exactly 4 files generated by Pillow in
# its own disposable temp directory. The actual Java canary never reads files.
HARNESS = r'''
import java.nio.file.Files;
import java.nio.file.Paths;
public class SyntheticCanaryHarness {
    public static void main(String[] args) throws Exception {
        final String[] labels = {"gradient", "checker", "colorbars", "impulse"};
        final int[] widths = {341, 199, 128, 65};
        final int[] heights = {173, 397, 256, 83};
        final byte[][] reference = new byte[4][];
        for (int i=0; i<4; i++) {
            reference[i] = Files.readAllBytes(Paths.get(args[0], labels[i] + ".rgb"));
        }
        IntelSyntheticCanary.Result result = IntelSyntheticCanary.verify(
            new IntelSyntheticCanary.RgbResize() {
                public byte[] resize(int w, int h, byte[] rgb) {
                    for (int i=0; i<4; i++) {
                        if (w == widths[i] && h == heights[i]) return reference[i].clone();
                    }
                    throw new IllegalArgumentException("Unknown synthetic geometry");
                }
            }
        );
        System.out.println(result.toJson());
    }
}
'''


@unittest.skipUnless(shutil.which("javac") and shutil.which("java"),
                     "JDK compiler and runtime unavailable")
class AndroidJavaSyntheticBridgeTests(unittest.TestCase):
    def compile_canary(self, workspace):
        source = ROOT / "IntelSyntheticCanary.java"
        self.assertTrue(source.is_file())
        # --release 8: Android-friendly bytecode and standard-library APIs.
        result = subprocess.run(
            ["javac", "-Xlint:-options", "--release", "8", "-d", str(workspace),
             str(source)], capture_output=True, text=True, timeout=45,
        )
        self.assertEqual(result.returncode, 0, result.stderr[:1000])

    def test_headless_java_source_and_tensor_sentinel_without_images(self):
        with tempfile.TemporaryDirectory(prefix="fictional-java-pixels-") as tmp:
            root = Path(tmp)
            self.compile_canary(root)
            result = subprocess.run(
                ["java", "-cp", str(root), "IntelSyntheticCanary", "--self-test"],
                capture_output=True, text=True, timeout=30,
            )
            self.assertEqual(result.returncode, 0, result.stderr[:1000])
            report = json.loads(result.stdout)
            self.assertEqual(report["checked_patterns"], 4)
            self.assertEqual(report["passing_patterns"], 1)
            self.assertFalse(report["all_four_exact"])
            for key in ("private_media_used", "production_approved",
                        "auto_confirm_allowed",
                        "real_model_or_android_runtime_verified"):
                self.assertFalse(report[key])
            for private in ("/storage", "photo_uid", "secret", "embedding"):
                self.assertNotIn(private, result.stdout)
            unsupported = subprocess.run(
                ["java", "-cp", str(root), "IntelSyntheticCanary", "--path",
                 "/private/photo.jpg"], capture_output=True, text=True,
                timeout=30)
            self.assertEqual(unsupported.returncode, 2)
            self.assertNotIn("private/photo", unsupported.stderr)

    def test_java_matches_all_four_stdlib_synthetic_reference_goldens(self):
        import hashlib
        with tempfile.TemporaryDirectory(prefix="fictional-pil-to-java-") as tmp:
            root = Path(tmp)
            self.compile_canary(root)
            for name, w, h in PROBES:
                raw = artificial_rgb(name, w, h)
                resized = synthetic_pillow_bilinear(name, w, h)
                self.assertEqual(hashlib.sha256(resized).hexdigest(),
                                 REFERENCE_SHA256[name]["resized_rgb"])
                (root / (name + ".rgb")).write_bytes(resized)
            (root / "SyntheticCanaryHarness.java").write_text(
                HARNESS, encoding="utf-8")
            compiled = subprocess.run(
                ["javac", "-Xlint:-options", "--release", "8",
                 "-cp", str(root), "-d", str(root),
                 str(root / "SyntheticCanaryHarness.java")],
                capture_output=True, text=True, timeout=45)
            self.assertEqual(compiled.returncode, 0, compiled.stderr[:1000])

            def run_harness():
                proc = subprocess.run(
                    ["java", "-cp", str(root), "SyntheticCanaryHarness",
                     str(root)], capture_output=True, text=True, timeout=30)
                self.assertEqual(proc.returncode, 0, proc.stderr[:1000])
                return json.loads(proc.stdout)

            positive = run_harness()
            self.assertTrue(positive["all_four_exact"])
            self.assertEqual(positive["passing_patterns"], 4)
            self.assertFalse(positive["production_approved"])
            # A one-bit mutation in a generated RGB buffer must cause refusal.
            path = root / "gradient.rgb"
            corrupted = bytearray(path.read_bytes())
            corrupted[33] ^= 1
            path.write_bytes(corrupted)
            negative = run_harness()
            self.assertFalse(negative["all_four_exact"])
            self.assertEqual(negative["passing_patterns"], 3)


if __name__ == "__main__":
    unittest.main(verbosity=2)
