HEADER = "// GENERATED by tools/visual_search_bench/pose_golden.py. Do not edit.\n"


def f32(v):
    """A Kotlin Float literal that round-trips the float32 value."""
    v = float(np.float32(v))
    if np.isnan(v):
        return "Float.NaN"
    return repr(v) + "f"


def floats(a, per_line=8):
    a = np.asarray(a, np.float32).ravel()
    lines = [", ".join(f32(x) for x in a[i:i + per_line]) for i in range(0, len(a), per_line)]
    return "floatArrayOf(\n" + ",\n".join("            " + ln for ln in lines) + ",\n        )"


def doubles(a):
    return "doubleArrayOf(" + ", ".join(repr(float(x)) for x in np.ravel(a)) + ")"


def ints(a):
    return "intArrayOf(" + ", ".join(str(int(x)) for x in np.ravel(a)) + ")"


# ---- synthetic inputs (the Kotlin tests rebuild the formula ones) ----------------

def argb_formula(w, h):
    """Same formula as BlazePoseMathTest.formulaImage: RGB from integer arithmetic."""
    y, x = np.mgrid[0:h, 0:w]
    r = (x * 37 + y * 11) % 256
    g = (x * x + 3 * y) % 256
    b = (x * y * 5 + 17) % 256
    return np.stack([r, g, b], -1).astype(np.uint8)


def detector_outputs():
    """Same formula as BlazePoseMathTest.detectorOutputs (float32 from integers)."""
    i = np.arange(blazepose.ssd_anchors().shape[0])[:, None]
    j = np.arange(12)[None, :]
    reg = (((i * 7 + j * 13) % 97) - 48).astype(np.float32) * np.float32(0.5)
    cls = ((((i[:, 0] * 31) % 211) - 150).astype(np.float32) / np.float32(10.0))
    return reg, cls


def worlds(n=6, seed=468):
    """Synthetic 33-point bodies: a standing skeleton plus seeded noise per body."""
    rng = np.random.default_rng(seed)
    out = []
    for k in range(n):
        p = np.zeros((33, 3), np.float32)
        sx, hx = 0.18, 0.12
        p[pd.L_SH], p[pd.R_SH] = [sx, -0.5, 0], [-sx, -0.5, 0]
        p[pd.L_HIP], p[pd.R_HIP] = [hx, 0, 0], [-hx, 0, 0]
        p[pd.L_KN], p[pd.R_KN] = [hx, 0.45, 0.05], [-hx, 0.45, 0]
        p[pd.L_AN], p[pd.R_AN] = [hx, 0.9, 0], [-hx, 0.9, 0]
        p[pd.L_EL], p[pd.R_EL] = [sx + 0.3, -0.5, 0], [-sx - 0.05, -0.2, 0]
        p[pd.L_WR], p[pd.R_WR] = [sx + 0.6, -0.5, 0], [-sx - 0.05, 0.1, 0]
        p += rng.normal(0, 0.15 * (k + 1) / n, p.shape).astype(np.float32)
        if k == 3:
            p[:, 1] = -p[:, 1]  # inverted body
        out.append(p.astype(np.float32))
    return out


def rerank_order(sem, psim_q, present_q, w=0.15, k=50, pose_prior=0.3):
    """bench.rerank_p10's ranking for one query, with the tail kept in semantic order."""
    s = np.asarray(sem, np.float64)
    order = np.argsort(-s, kind="stable")
    cand = order[:k]
    score = s[cand]
    if present_q:
        score = score + w * np.nan_to_num(psim_q[cand] - pose_prior, nan=-pose_prior)
    top = cand[np.argsort(-score, kind="stable")]
    return np.concatenate([top, order[k:]]), np.concatenate([np.sort(score)[::-1], s[order[k:]]])


# ---- figure images for the on-device test ------------------------------------

FIG_W, FIG_H = 480, 640
BG = (240, 240, 240)
SKIN, SHIRT, PANTS = (220, 170, 140), (40, 80, 160), (50, 50, 60)
DARK, HAIR = (30, 30, 30), (60, 40, 20)
# Painted in order. cap: segment (a,b)-(c,d) with radius r; rect: [a,c] x [b,d];
# ell: centre (a,b), radii (c,d). Integer tests only, so Kotlin draws the same pixels.
SHAPES = [
    ("cap", 226, 336, 218, 396, 10, PANTS), ("cap", 218, 396, 214, 452, 9, PANTS),
    ("cap", 254, 336, 262, 396, 10, PANTS), ("cap", 262, 396, 266, 452, 9, PANTS),
    ("rect", 213, 248, 267, 340, 0, SHIRT),
    ("cap", 213, 254, 184, 296, 6, SHIRT), ("cap", 184, 296, 176, 340, 5, SKIN),
    ("cap", 267, 254, 296, 296, 6, SHIRT), ("cap", 296, 296, 304, 340, 5, SKIN),
    ("cap", 240, 240, 240, 250, 6, SKIN),
    ("ell", 240, 218, 19, 24, 0, SKIN),
    ("ell", 233, 213, 2, 2, 0, DARK), ("ell", 247, 213, 2, 2, 0, DARK),
    ("ell", 240, 200, 21, 11, 0, HAIR),
]
CROP_STEP = 7
FIGURES = ["standing", "mirrored", "upside_down", "blank"]


def inside(s, x, y):
    k, a, b, c, d, r, _ = s
    if k == "rect":
        return a <= x <= c and b <= y <= d
    if k == "ell":
        return (x - a) ** 2 * d * d + (y - b) ** 2 * c * c <= c * c * d * d
    vx, vy, wx, wy = c - a, d - b, x - a, y - b
    ll, t = vx * vx + vy * vy, wx * vx + wy * vy
    if t <= 0:
        return wx * wx + wy * wy <= r * r
    if t >= ll:
        return (x - c) ** 2 + (y - d) ** 2 <= r * r
    cr = wx * vy - wy * vx
    return cr * cr <= r * r * ll


def figure(name):
    img = np.zeros((FIG_H, FIG_W, 3), np.uint8)
    img[:] = BG
    if name == "blank":
        return img
    for y in range(FIG_H):
        for x in range(FIG_W):
            for s in reversed(SHAPES):
                if inside(s, x, y):
                    img[y, x] = s[6]
                    break
    if name == "mirrored":
        img = img[:, ::-1].copy()
    elif name == "upside_down":
        img = img[::-1, ::-1].copy()
    return img


# ---- writers -----------------------------------------------------------------

def write_jvm(path, bp):
    ws = worlds()
    descs = [pd.descriptor(w) for w in ws]
    sims = [[pd.similarity(a, b) for b in descs] for a in descs]

    rng = np.random.default_rng(4680)
    n = 64
    sem = rng.uniform(0.2, 0.8, n).astype(np.float32)
    pose_of = rng.integers(-1, len(ws), n)  # -1 = no body
    q = descs[0]
    psim = np.array([np.nan if p < 0 else pd.similarity(q, descs[p]) for p in pose_of], np.float64)
    order, scores = rerank_order(sem.astype(np.float64), psim, True)
    order_none, _ = rerank_order(sem.astype(np.float64), psim, False)

    anchors = blazepose.ssd_anchors()

    # Letterbox (detector input) for an upscaled and a downscaled formula image.
    lb = {}
    for (w, h) in [(61, 40), (500, 300), (90, 211)]:
        rgb = argb_formula(w, h)
        ratio = min(blazepose.DET_SIZE / h, blazepose.DET_SIZE / w)
        nh, nw = int(h * ratio), int(w * ratio)
        img = cv2.resize(rgb.astype(np.float32) / 127.5 - 1.0, (nw, nh))
        left, top = (blazepose.DET_SIZE - nw) // 2, (blazepose.DET_SIZE - nh) // 2
        canvas = np.zeros((blazepose.DET_SIZE, blazepose.DET_SIZE, 3), np.float32)
        canvas[top:top + nh, left:left + nw] = img
        nchw = canvas.transpose(2, 0, 1).ravel()
        idx = np.arange(0, nchw.size, 997)
        lb[(w, h)] = (left, top, idx, nchw[idx], float(np.float64(nchw.astype(np.float64).sum())))

    # Detector post-processing on formula outputs, through the real detect() code path.
    reg, cls = detector_outputs()

    class FakeDet:
        def run(self, _names, _feeds):
            return [cls[None, :, None], reg[None]] if bp.det_cls == 0 else [reg[None], cls[None, :, None]]

    real = bp.det
    bp.det = FakeDet()
    dets = {}
    for (w, h) in [(640, 480), (300, 900)]:
        dets[(w, h)] = bp.detect(np.zeros((h, w, 3), np.uint8))
    bp.det = real

    # RoI matrix and crop for one detection on a formula image.
    w, h = 120, 90
    rgb = argb_formula(w, h)
    hip, full = np.array([61.5, 50.25], np.float32), np.array([40.0, 12.75], np.float32)
    r = np.linalg.norm(hip - full)
    ang = np.pi / 2 - np.arctan2(-(full[1] - hip[1]), full[0] - hip[0])
    ang = ang - 2 * np.pi * np.floor((ang + np.pi) / (2 * np.pi))
    deg = float(np.rad2deg(ang))
    m = cv2.getRotationMatrix2D((float(hip[0]), float(hip[1])), deg, 1.0)
    s = blazepose.POSE_SIZE / (2 * r)
    a = np.vstack([m, [0, 0, 1]])
    t = np.array([[s, 0, blazepose.POSE_SIZE / 2 - s * hip[0]], [0, s, blazepose.POSE_SIZE / 2 - s * hip[1]], [0, 0, 1]])
    fwd = (t @ a)[:2]
    crop = cv2.warpAffine(rgb, fwd, (blazepose.POSE_SIZE, blazepose.POSE_SIZE), flags=cv2.INTER_AREA,
                          borderMode=cv2.BORDER_CONSTANT, borderValue=0)
    crop_bytes = crop.tobytes()
    crop_hex = crop_bytes[::CROP_STEP].hex()

    raw = ((np.arange(117) * 17 % 23) - 11).astype(np.float32) / np.float32(7.0)
    world = raw.reshape(39, 3)[:33]
    rot = cv2.getRotationMatrix2D((0, 0), deg, 1.0)[:, :2]
    unrot = np.c_[world[:, :2] @ rot, world[:, 2]].astype(np.float32)

    k = []
    k.append(HEADER)
    k.append("package nl.atlas.gallery.featurevisual.pose\n\n")
    k.append("/** Python reference values for [BlazePoseMathTest], [PoseDescriptorTest] and [PoseRerankTest]. */\n")
    k.append("object BlazePoseGolden {\n")
    k.append("    val worlds: List<FloatArray> = listOf(\n")
    for wv in ws:
        k.append("        " + floats(wv, 9) + ",\n")
    k.append("    )\n")
    k.append("    val descriptors: List<FloatArray> = listOf(\n")
    for d in descs:
        k.append("        " + floats(d, 9) + ",\n")
    k.append("    )\n")
    k.append("    val similarities: List<FloatArray> = listOf(\n")
    for row in sims:
        k.append("        " + floats(row, 6) + ",\n")
    k.append("    )\n\n")
    k.append("    /** Re-rank: query = descriptors[0]; candidate i has semantic score semantic[i] and pose\n")
    k.append("     *  descriptors[poseOf[i]], or no body when poseOf[i] is -1. */\n")
    k.append(f"    val semantic = {floats(sem, 8)}\n")
    k.append(f"    val poseOf = {ints(pose_of)}\n")
    k.append(f"    val rerankOrder = {ints(order)}\n")
    k.append(f"    val rerankScores = {floats(scores, 8)}\n")
    k.append(f"    val semanticOrder = {ints(order_none)}\n\n")
    k.append(f"    const val ANCHOR_COUNT = {anchors.shape[0]}\n")
    sample = [0, 1, 1567, 1568, 1569, 1960, 2253]
    k.append(f"    val anchorIndices = {ints(sample)}\n")
    k.append(f"    val anchorValues = {floats(anchors[sample].ravel(), 8)}\n\n")
    k.append("    class Letterbox(val width: Int, val height: Int, val left: Int, val top: Int,\n")
    k.append("                    val sampleIndices: IntArray, val samples: FloatArray, val sum: Double)\n")
    k.append("    val letterboxes = listOf(\n")
    for (w0, h0), (left, top, idx, vals, total) in lb.items():
        k.append(f"        Letterbox({w0}, {h0}, {left}, {top}, {ints(idx)},\n            {floats(vals, 8)}, {total!r}),\n")
    k.append("    )\n\n")
    k.append("    /** detect() on the formula detector outputs: frame size -> score, hip x/y, full x/y. */\n")
    k.append("    class Detection(val width: Int, val height: Int, val score: Float, val point: FloatArray)\n")
    k.append("    val detections = listOf(\n")
    for (w0, h0), d in dets.items():
        sc, hp, fl = d
        k.append(f"        Detection({w0}, {h0}, {f32(sc)}, {floats([hp[0], hp[1], fl[0], fl[1]], 4)}),\n")
    k.append("    )\n\n")
    k.append(f"    const val ROI_WIDTH = {w}\n    const val ROI_HEIGHT = {h}\n")
    k.append(f"    val roiHipFull = {floats([hip[0], hip[1], full[0], full[1]], 4)}\n")
    k.append(f"    const val ROI_DEGREES = {deg!r}\n")
    k.append(f"    val roiForward = {doubles(fwd)}\n")
    k.append(f"    /** cv2.warpAffine crop (256 x 256 x 3 RGB bytes): every CROP_STEP-th byte, as hex. */\n")
    k.append(f"    const val CROP_STEP = {CROP_STEP}\n")
    k.append(f"    const val CROP_HEX = \"{crop_hex}\"\n\n")
    k.append(f"    val unrotated = {floats(unrot, 9)}\n")
    k.append("}\n")
    with open(path, "w") as fh:
        fh.write("".join(k))


def write_android(path, bp, models):
    out = {}
    for name in FIGURES:
        img = figure(name)
        d = bp.detect(img)
        w = bp.world_landmarks(img)
        out[name] = (None if d is None else float(d[0]), None if w is None else pd.descriptor(w))
    k = [HEADER, "package nl.atlas.gallery.featurevisual\n\n"]
    k.append("/** Host ONNX Runtime results of blazepose.py + pose_descriptor.py on the formula figures. */\n")
    k.append("object PoseGolden {\n")
    k.append(f"    const val DETECTOR_SHA256 = \"{models[0]}\"\n")
    k.append(f"    const val LANDMARK_SHA256 = \"{models[1]}\"\n")
    k.append("    class Figure(val name: String, val detScore: Float?, val descriptor: FloatArray?)\n")
    k.append("    val all = listOf(\n")
    for name, (sc, d) in out.items():
        k.append(f"        Figure(\"{name}\", {'null' if sc is None else f32(sc)}, "
                 f"{'null' if d is None else floats(d, 9)}),\n")
    k.append("    )\n}\n")
    with open(path, "w") as fh:
        fh.write("".join(k))
    return {n: (sc, d is not None) for n, (sc, d) in out.items()}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zoo-dir", required=True)
    ap.add_argument("--jvm")
    ap.add_argument("--android")
    a = ap.parse_args()
    pins = json.load(open(os.path.join(HERE, "models.json")))
    det = os.path.join(a.zoo_dir, "person_detection_mediapipe_2023mar.onnx")
    pose = os.path.join(a.zoo_dir, "pose_estimation_mediapipe_2023mar.onnx")
    shas = (sha256(det), sha256(pose))
    assert shas == (pins["mediapipe_person_detector"]["sha256"], pins["mediapipe_pose"]["sha256"]), shas
    bp = blazepose.BlazePose(det, pose, threads=1)
    if a.jvm:
        write_jvm(a.jvm, bp)
    if a.android:
        print(json.dumps(write_android(a.android, bp, shas)))


if __name__ == "__main__":
    main()
